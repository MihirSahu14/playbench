#!/usr/bin/env python3
"""playbench art: placeholder sprites, atlas packing, Aseprite export, naming lint.
Every generated image is a `_placeholder` file recorded in art/PLACEHOLDERS.json; humans own final art.
Pillow is imported only by the commands that draw. Exit codes: 0 ok, 1 problems, 2 usage or environment."""
import argparse, contextlib, io, json, math, os, re, shutil, subprocess, sys, tempfile
from pathlib import Path

NAME = re.compile(r'[a-z0-9]+(?:_[a-z0-9]+)*')
HEX = re.compile(r'#[0-9a-fA-F]{6}')
ROLES = ('bg', 'text', 'link', 'button')
NOTE = 'generated by playbench art.py; replace or disclose before release'


def aseprite_bin():
    """The one resolver for the Aseprite binary; the selftest swaps it for a stub."""
    return os.environ.get('ASEPRITE') or shutil.which('aseprite')


def pil():
    try:
        from PIL import Image, ImageDraw, PngImagePlugin
    except ImportError:
        print(f'Pillow not installed for {sys.executable}: run "{sys.executable}" -m pip install pillow')
        raise SystemExit(2)
    return Image, ImageDraw, PngImagePlugin


def die(msg):
    print(f'ERROR {msg}')
    raise SystemExit(2)


def bible(game):
    """art/bible.md (Contract C6) -> (palette {name: hex}, tile, [(sprite, anim, frames)])."""
    p = game / 'art' / 'bible.md'
    if not p.exists(): return {}, 16, []
    pal, tile, rows, sec = {}, 16, [], ''
    for line in p.read_text(encoding='utf-8-sig').splitlines():
        s = line.strip()
        if s.startswith('## '): sec = s[3:].strip().lower(); continue
        if sec == 'palette' and (m := re.fullmatch(r'-\s*([\w -]+?)\s*:\s*(#[0-9a-fA-F]{6})\b.*', s)):
            pal[m[1].lower()] = m[2].lower()
        elif sec == 'pixel density' and (m := re.fullmatch(r'-\s*tile\s*:\s*(\d+).*', s, re.I)):
            tile = int(m[1])
        elif sec == 'animations' and s.startswith('|'):
            c = [x.strip() for x in s.strip('|').split('|')]
            if len(c) >= 3 and c[2].isdigit(): rows.append((c[0], c[1], int(c[2])))  # skips header and ---
    return pal, tile, rows


def rgb(spec, pal):
    if HEX.fullmatch(spec or ''): return spec.lower()
    if (spec or '').lower() in pal: return pal[spec.lower()]
    die(f'unknown color {spec!r}: use #rrggbb or a palette name from art/bible.md ({", ".join(pal) or "no bible"})')


def load_ph(game):
    p = game / 'art' / 'PLACEHOLDERS.json'
    data = json.loads(p.read_text(encoding='utf-8-sig')) if p.exists() else {'placeholders': []}
    if not isinstance(data, dict) or not isinstance(data.get('placeholders', []), list):
        raise ValueError('expected {"placeholders": [{"path": ..., "source": ..., "note": ...}]}')
    return data


def record(game, rel, note, source='generated'):
    """Add or update (dedupe by path) one PLACEHOLDERS.json entry, keeping the others."""
    try: data = load_ph(game)
    except ValueError as e: die(f'art/PLACEHOLDERS.json is broken ({e}): fix it, then rerun')
    ents = [e for e in data.setdefault('placeholders', []) if not (isinstance(e, dict) and e.get('path') == rel)]
    data['placeholders'] = ents + [{'path': rel, 'source': source, 'note': note}]
    (game / 'art').mkdir(parents=True, exist_ok=True)
    (game / 'art' / 'PLACEHOLDERS.json').write_text(json.dumps(data, indent=2) + '\n', 'utf-8')


def meta(PngImagePlugin):
    m = PngImagePlugin.PngInfo()
    m.add_text('playbench', 'placeholder')  # a tEXt chunk; never stripped
    return m


# ---------- placeholder ----------
def draw(name, anim, frames, w, h, color, game):
    Image, ImageDraw, PngImagePlugin = pil()
    for n in (name, anim or 'x'):
        if not NAME.fullmatch(n) or n.endswith('placeholder'): die(f'{n!r} must be lowercase snake_case, without "placeholder"')
    if not (4 <= w <= 1024 and 4 <= h <= 1024 and 1 <= frames <= 64): die('size 4..1024 px per side, frames 1..64')
    c = tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))
    dark, light = tuple(v * 6 // 10 for v in c), tuple(v + (255 - v) // 2 for v in c)
    ink = (0, 0, 0) if sum(c) > 384 else (255, 255, 255)
    img = Image.new('RGBA', (w * frames, h))
    for f in range(frames):
        fr = Image.new('RGBA', (w, h), c)  # one image per frame, so hatching can't spill into a neighbour
        d = ImageDraw.Draw(fr)
        for k in range(-h, w, 6):  # diagonal hatching reads as "not final"
            d.line([(k, 0), (k + h, h)], fill=light)
        d.rectangle([0, 0, w - 1, h - 1], outline=dark)
        for i in range(min(f + 1, w - 4)):  # frame index: f+1 pixels in row 2
            fr.putpixel((2 + i, 2), ink)
        img.paste(fr, (f * w, 0))
    rel = f'art/{name}{"_" + anim if anim else ""}_placeholder.png'
    record(game, rel, f'{w}x{h}, {frames} frames, {NOTE}')  # first, so a broken PLACEHOLDERS.json leaves no unlisted image
    img.save(game / rel, pnginfo=meta(PngImagePlugin))
    print(f'PLACEHOLDER={rel}')
    return rel


def placeholder(game, a):
    pal = bible(game)[0]
    m = re.fullmatch(r'(\d+)x(\d+)', a.size) or die(f'--size must look like 16x16, got {a.size!r}')
    extra = [k for k in pal if k not in ROLES]
    color = rgb(a.color, pal) if a.color else pal.get(extra[0] if extra else 'button', '#e94560')
    draw(a.name, a.anim, a.frames, int(m[1]), int(m[2]), color, game)
    return 0


def placeholders(game):
    pal, tile, rows = bible(game)
    if not rows: die('no rows in the ## Animations table of art/bible.md (run the art skill first)')
    cols = [v for k, v in pal.items() if k not in ROLES] or [pal[k] for k in ROLES if k in pal] or ['#e94560']
    for i, (sprite, anim, frames) in enumerate(rows):
        anim = '' if anim in ('', '-') else anim
        final = game / 'art' / f'{sprite}{"_" + anim if anim else ""}.png'
        if final.exists():
            print(f'SKIP {final.name}: final art exists')
            continue
        draw(sprite, anim, frames, tile, tile, cols[i % len(cols)], game)
    return 0


# ---------- pack ----------
def game_root(p):
    return next((d for d in [p, *p.parents] if (d / 'studio.json').exists()), None)


def shelf(sizes, pad):
    """sizes {name: (w, h)} -> ({name: (x, y)}, W, H). Shelf packing, tallest first."""
    widest = max(w for w, h in sizes.values()) + pad
    if widest > 4096: die('a sprite is wider than 4096 px')
    area = sum((w + pad) * (h + pad) for w, h in sizes.values())
    W = max(2 ** math.ceil(math.log2(max(math.sqrt(area), widest, 1))), 1)
    W = min(W, 4096)
    pos, x, y, row = {}, 0, 0, 0
    for n in sorted(sizes, key=lambda n: (-sizes[n][1], n)):
        w, h = sizes[n]
        if x + w + pad > W: x, y, row = 0, y + row, 0
        pos[n], x, row = (x, y), x + w + pad, max(row, h + pad)
    return pos, W, max(pos[n][1] + sizes[n][1] for n in pos)


def pack(inputs, out, pad, pot):
    Image, _, PngImagePlugin = pil()
    files = []
    for i in map(Path, inputs):
        files += [f for f in sorted(i.glob('*.png')) if not ours(f)] if i.is_dir() else [i]
    base = Path(out).resolve()
    if any('_placeholder' in f.stem for f in files) and not base.name.endswith('_placeholder'):
        base = base.with_name(base.name + '_placeholder')
        print(f'NOTE output renamed to {base.name}: placeholder inputs make a placeholder atlas')
    png, js = base.parent / f'{base.name}.png', base.parent / f'{base.name}.json'
    files = [f for f in files if f.resolve() != png]
    if not files: die('no PNG inputs')
    imgs = {}
    for f in files:
        if f.stem in imgs: die(f'two inputs named {f.stem}')
        try: imgs[f.stem] = Image.open(f).convert('RGBA')
        except OSError as e: die(f'{f}: not a readable image ({e})')
    pos, W, H = shelf({n: im.size for n, im in imgs.items()}, pad)
    if pot: H = 2 ** math.ceil(math.log2(H))
    if H > 4096: print(f'WARN atlas height {H} > 4096: some GPUs reject it; split the inputs')
    atlas = Image.new('RGBA', (W, H))
    frames = {}
    for n, (x, y) in pos.items():
        w, h = imgs[n].size
        atlas.paste(imgs[n], (x, y))
        frames[n] = {'frame': {'x': x, 'y': y, 'w': w, 'h': h}, 'rotated': False, 'trimmed': False,
                     'spriteSourceSize': {'x': 0, 'y': 0, 'w': w, 'h': h}, 'sourceSize': {'w': w, 'h': h}}
    base.parent.mkdir(parents=True, exist_ok=True)
    ph = base.name.endswith('_placeholder')
    atlas.save(png, pnginfo=meta(PngImagePlugin) if ph else None)
    js.write_text(json.dumps({'frames': frames, 'meta': {'app': 'playbench art.py', 'version': '1.0', 'image': png.name,
                                                          'format': 'RGBA8888', 'size': {'w': W, 'h': H}, 'scale': '1'}},
                             indent=1) + '\n', 'utf-8')
    if ph:
        game = game_root(base.parent)
        if game:
            for p in (png, js):  # both carry the _placeholder tag, so lint wants both listed
                record(game, Path(os.path.relpath(p, game)).as_posix(), f'atlas of {len(imgs)} sprites incl. placeholders, {NOTE}')
        else:
            print('WARN no studio.json above the output: atlas not recorded in art/PLACEHOLDERS.json')
    print(f'ATLAS={png}\nDATA={js}\nSIZE={W}x{H} FRAMES={len(frames)}')
    return 0


def ours(png):
    """True for an atlas this script wrote (sibling JSON with our meta.app): never repack it into a new atlas."""
    with contextlib.suppress(OSError, ValueError, AttributeError):
        return json.loads(png.with_suffix('.json').read_text(encoding='utf-8-sig'))['meta']['app'] == 'playbench art.py'
    return False


# ---------- aseprite ----------
def aseprite(src, out):
    exe = aseprite_bin()
    if not exe: die('Aseprite not found: set ASEPRITE=<path to the aseprite executable>')
    if not Path(src).is_file(): die(f'not found: {src}')
    base = Path(out)
    base.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([exe, '-b', str(src), '--sheet', f'{base}.png', '--data', f'{base}.json',
                        '--format', 'json-hash', '--sheet-pack', '--list-tags'])
    print(f'ASEPRITE_EXIT={r.returncode}')
    return r.returncode


# ---------- lint ----------
def lint(game):
    art, probs = game / 'art', []
    files = sorted(p for p in art.rglob('*') if p.is_file()) if art.is_dir() else []
    rels = [p.relative_to(game).as_posix() for p in files]
    try:
        listed = {e.get('path', '').replace('\\', '/') for e in load_ph(game).get('placeholders', []) if isinstance(e, dict)}
    except ValueError as e:
        listed = set()
        probs.append(f'art/PLACEHOLDERS.json is not valid JSON: {e}')
    for p, rel in zip(files, rels):
        if rel == 'art/PLACEHOLDERS.json' or p.name.startswith('.') or p.name in ('Thumbs.db', 'desktop.ini'): continue  # OS/git files
        stem, ext = p.stem, p.suffix
        if ' ' in rel: probs.append(f'{rel}: space in name')
        if ext != ext.lower(): probs.append(f'{rel}: extension must be lowercase')
        if not re.fullmatch(r'[a-z0-9_]+', stem): probs.append(f'{rel}: name must be lowercase a-z 0-9 _')
        if 'placeholder' in stem.lower() and not (stem.lower().endswith('_placeholder') and stem.lower().count('placeholder') == 1):
            probs.append(f'{rel}: _placeholder must be the last part of the name')
        if stem.lower().endswith('_placeholder') and rel not in listed:
            probs.append(f'{rel}: placeholder not listed in art/PLACEHOLDERS.json')
        if ext.lower() == '.json':
            with contextlib.suppress(ValueError, OSError, AttributeError):
                img = json.loads(p.read_text(encoding='utf-8-sig')).get('meta', {}).get('image')
                if img and not (p.parent / img).exists(): probs.append(f'{rel}: atlas image {img} not found')
    probs += [f'{e}: listed in art/PLACEHOLDERS.json but the file is missing' for e in sorted(listed) if e and not (game / e).is_file()]
    probs += [f'{e}: listed with different case than the file' for e in sorted(listed)
              if e.startswith('art/') and e not in rels and (game / e).is_file()]
    probs += case_dups(rels)
    print(f'LINT {len(probs)} problems' if probs else 'LINT PASS')
    for p in probs: print(f'  - {p}')
    return 1 if probs else 0


def case_dups(rels):
    """Paths equal except for case: fine on Windows, broken on itch's case-sensitive server."""
    seen, out = {}, []
    for rel in rels:
        if rel.lower() in seen: out.append(f'{rel}: same name as {seen[rel.lower()]} except for case')
        seen.setdefault(rel.lower(), rel)
    return out


# ---------- selftest ----------
def stub(dirpath, name, body):
    """Fake executable `name` in dirpath that runs python source `body` with this interpreter (Contract C7)."""
    py = dirpath / f'{name}_stub.py'
    py.write_text(body, 'utf-8')
    if os.name == 'nt':
        exe = dirpath / f'{name}.cmd'
        exe.write_text(f'@"{sys.executable}" "{py}" %*\n', 'utf-8')
    else:
        exe = dirpath / name
        exe.write_text(f'#!/bin/sh\nexec "{sys.executable}" "{py}" "$@"\n', 'utf-8')
        exe.chmod(0o755)
    return exe


def selftest():
    global aseprite_bin
    real_bin, tmp = aseprite_bin, Path(tempfile.mkdtemp(prefix='art-selftest-'))

    def cap(fn, *a):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            try: code = fn(*a)
            except SystemExit as e: code = e.code
        return code, buf.getvalue()

    def game(name, bible_md=None):
        g = tmp / name
        (g / 'art').mkdir(parents=True)
        (g / 'studio.json').write_text('{}', 'utf-8')
        if bible_md: (g / 'art' / 'bible.md').write_text(bible_md, 'utf-8')
        return g
    try:
        try:
            import PIL; have_pil = True
        except ImportError:
            have_pil = False
        if have_pil:
            from PIL import Image
            # placeholder: 4 frames of 16x16 -> 64x16 with the tEXt chunk; rerun does not duplicate the entry
            g = game('ph')
            args = ['placeholder', str(g), '--name', 'hero', '--anim', 'run', '--frames', '4', '--size', '16x16', '--color', '#3366cc']
            for _ in range(2): assert cap(main, args)[0] == 0
            png = g / 'art' / 'hero_run_placeholder.png'
            im = Image.open(png)
            assert im.size == (64, 16)
            assert [sum(im.getpixel((f * 16 + 2 + i, 2))[:3] == (255, 255, 255) for i in range(12)) for f in range(4)] == [1, 2, 3, 4]
            assert b'tEXtplaybench\x00placeholder' in png.read_bytes()
            ents = load_ph(g)['placeholders']
            assert ents == [{'path': 'art/hero_run_placeholder.png', 'source': 'generated',
                             'note': f'16x16, 4 frames, {NOTE}'}], ents
            assert cap(main, ['placeholder', str(g), '--name', 'Hero'])[0] == 2
            (g / 'art' / 'PLACEHOLDERS.json').write_text('[]', 'utf-8')  # wrong shape: clean exit 2, no unlisted image
            assert cap(main, ['placeholder', str(g), '--name', 'bad'])[0] == 2 and not (g / 'art' / 'bad_placeholder.png').exists()
            print('ok placeholder')
            # placeholders: 3 rows, one with final art -> 2 files
            g = game('phs', '# Art bible: t\n## Palette\n- bg: #000000\n- text: #ffffff\n- link: #ffcc00\n- button: #e94560\n'
                            '- leaf: #22aa44\n## Pixel density\n- tile: 8\n- scale: 3\n## Animations\n'
                            '| sprite | anim | frames | fps |\n|---|---|---|---|\n| hero | run | 4 | 10 |\n'
                            '| bat | fly | 2 | 8 |\n| coin | spin | 6 | 12 |\n')
            Image.new('RGBA', (8, 8)).save(g / 'art' / 'coin_spin.png')
            code, out = cap(placeholders, g)
            assert code == 0 and 'SKIP coin_spin.png' in out, out
            assert sorted(p.name for p in (g / 'art').glob('*_placeholder.png')) == ['bat_fly_placeholder.png', 'hero_run_placeholder.png']
            assert Image.open(g / 'art' / 'hero_run_placeholder.png').size == (32, 8)
            assert Image.open(g / 'art' / 'bat_fly_placeholder.png').getpixel((4, 7))[:3] != (0, 0, 0)
            assert len(load_ph(g)['placeholders']) == 2
            print('ok placeholders')
            # pack: 3 sizes, padding 2
            src = tmp / 'src'
            src.mkdir()
            for i, (w, h) in enumerate([(10, 6), (4, 12), (7, 7)]):
                im = Image.new('RGBA', (w, h), (40 * i, 200, 255 - 40 * i, 255))
                im.putpixel((0, 0), (i, 1, 2, 255))
                im.save(src / f's{i}.png')
            assert cap(pack, [str(src)], str(tmp / 'out' / 'atlas'), 2, False)[0] == 0
            meta_ = json.loads((tmp / 'out' / 'atlas.json').read_text())
            atlas = Image.open(tmp / 'out' / 'atlas.png')
            W, H = meta_['meta']['size']['w'], meta_['meta']['size']['h']
            assert atlas.size == (W, H) and meta_['meta']['image'] == 'atlas.png' and W & (W - 1) == 0
            rects = []
            for n, fr in meta_['frames'].items():
                f = fr['frame']
                assert f['x'] >= 0 and f['y'] >= 0 and f['x'] + f['w'] <= W and f['y'] + f['h'] <= H, (n, f)
                s = Image.open(src / f'{n}.png').convert('RGBA')
                assert atlas.getpixel((f['x'], f['y'])) == s.getpixel((0, 0))
                assert atlas.crop((f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h'])).tobytes() == s.tobytes()
                rects.append((f['x'], f['y'], f['x'] + f['w'] + 2, f['y'] + f['h'] + 2))
            for i, a in enumerate(rects):
                for b in rects[i + 1:]:
                    assert a[2] <= b[0] or b[2] <= a[0] or a[3] <= b[1] or b[3] <= a[1], (a, b)
            assert cap(pack, [str(src / 's0.png')], str(tmp / 'out' / 'pot'), 0, True)[0] == 0
            assert Image.open(tmp / 'out' / 'pot.png').size == (16, 8)
            (tmp / 'out' / 's9.png').write_bytes(b'x')
            for f in ('atlas.png', 'atlas.json', 'pot.png', 'pot.json'): shutil.copy(tmp / 'out' / f, src / f)
            code, out = cap(pack, [str(src)], str(tmp / 'out' / 'again'), 2, False)  # our old atlases are not repacked
            assert code == 0 and 'FRAMES=3' in out, out
            assert cap(pack, [str(tmp / 'out')], str(tmp / 'x'), 2, False)[0] == 2  # unreadable s9.png
            print('ok pack')
            # pack with a placeholder input -> base renamed and recorded
            g = tmp / 'phs'
            code, out = cap(pack, [str(g / 'art')], str(g / 'build' / 'atlas'), 2, False)
            assert code == 0 and 'renamed' in out and (g / 'build' / 'atlas_placeholder.png').exists(), out
            paths = {e['path'] for e in load_ph(g)['placeholders']}
            assert {'build/atlas_placeholder.png', 'build/atlas_placeholder.json'} <= paths, paths
            assert b'tEXtplaybench\x00placeholder' in (g / 'build' / 'atlas_placeholder.png').read_bytes()
            print('ok pack placeholder')
        else:
            print(f'SKIP placeholder, placeholders, pack: Pillow not installed for {sys.executable}')

        # aseprite: a C7 stub records argv and writes the --sheet/--data files
        bin_dir = tmp / 'bin'
        bin_dir.mkdir()
        exe = stub(bin_dir, 'aseprite', 'import json, sys\na = sys.argv[1:]\n'
                   f'open(r"{bin_dir / "argv.json"}", "w").write(json.dumps(a))\n'
                   'open(a[a.index("--sheet") + 1], "wb").write(b"png")\nopen(a[a.index("--data") + 1], "w").write("{}")\n')
        (tmp / 'hero.aseprite').write_bytes(b'ase')
        aseprite_bin = lambda: str(exe)
        code, out = cap(aseprite, str(tmp / 'hero.aseprite'), str(tmp / 'ase' / 'hero'))
        argv = json.loads((bin_dir / 'argv.json').read_text())
        assert code == 0, out
        assert {'-b', '--sheet', '--data', 'json-hash'} <= set(argv), argv
        assert (tmp / 'ase' / 'hero.png').exists() and (tmp / 'ase' / 'hero.json').exists()
        aseprite_bin = lambda: None
        code, out = cap(aseprite, str(tmp / 'hero.aseprite'), str(tmp / 'ase' / 'x'))
        assert code == 2 and 'ASEPRITE=' in out, out
        print('ok aseprite stub')
        print('SKIP aseprite real: ' + (f'found {real_bin()}, but only the stub runs here' if real_bin() else 'not installed'))

        # lint
        g = game('lint')
        (g / 'art' / 'hero_run.png').write_bytes(b'x')
        (g / 'art' / 'bat_placeholder.png').write_bytes(b'x')
        (g / 'art' / 'atlas.json').write_text('{"meta": {"image": "hero_run.png"}}')
        (g / 'art' / 'PLACEHOLDERS.json').write_text('{"placeholders":[{"path":"art\\\\bat_placeholder.png","source":"ai","note":"x"}]}')
        (g / 'art' / '.gitkeep').write_bytes(b'')
        code, out = cap(lint, g)
        assert code == 0 and 'LINT PASS' in out, out
        (g / 'art' / 'Hero Run.PNG').write_bytes(b'x')
        (g / 'art' / 'x_placeholder.png').write_bytes(b'x')
        (g / 'art' / 'sub').mkdir()
        (g / 'art' / 'sub' / 'a.png').write_bytes(b'x')
        (g / 'art' / 'sub' / 'A.png').write_bytes(b'x')  # same file on a case-insensitive disk (Windows, macOS)
        (g / 'art' / 'PLACEHOLDERS.json').write_text('{"placeholders":[{"path":"art/bat_placeholder.png"},{"path":"art/gone_placeholder.png"}]}')
        code, out = cap(lint, g)
        assert code == 1 and 'LINT ' in out and 'problems' in out, out
        assert 'bat_placeholder' not in out and '.gitkeep' not in out, out
        for needle in ('Hero Run.PNG: space', 'Hero Run.PNG: extension', 'x_placeholder.png: placeholder not listed',
                       'gone_placeholder.png: listed'):
            assert needle in out, (needle, out)
        if len(list((g / 'art' / 'sub').iterdir())) == 2: assert 'except for case' in out, out
        (g / 'art' / 'PLACEHOLDERS.json').write_text('[]')
        assert 'not valid JSON' in cap(lint, g)[1]
        assert case_dups(['art/a.png', 'art/b.png', 'art/A.png']) == ['art/A.png: same name as art/a.png except for case']
        print('ok lint')
    finally:
        aseprite_bin = real_bin
        shutil.rmtree(tmp, ignore_errors=True)
    print('ok art')
    return 0


def main(argv=None):
    with contextlib.suppress(AttributeError):
        sys.stdout.reconfigure(errors='replace')
    ap = argparse.ArgumentParser(prog='art.py', description='playbench art: placeholders, atlas, Aseprite export, naming lint.')
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('placeholder', help='one labelled placeholder sprite sheet')
    p.add_argument('game_dir')
    p.add_argument('--name', required=True)
    p.add_argument('--anim', default='')
    p.add_argument('--frames', type=int, default=1)
    p.add_argument('--size', default='16x16')
    p.add_argument('--color', help='palette name from art/bible.md or #rrggbb')
    sub.add_parser('placeholders', help='one sheet per ## Animations row of art/bible.md').add_argument('game_dir')
    p = sub.add_parser('pack', help='pack PNGs into <out>.png + <out>.json (TexturePacker JSON hash)')
    p.add_argument('inputs', nargs='+')
    p.add_argument('--out', required=True)
    p.add_argument('--padding', type=int, default=2)
    p.add_argument('--pot', action='store_true', help='round the height up to a power of two')
    p = sub.add_parser('aseprite', help='export an .aseprite file to a sheet + json-hash data')
    p.add_argument('file')
    p.add_argument('--out', required=True)
    sub.add_parser('lint', help='naming lint over art/').add_argument('game_dir')
    sub.add_parser('selftest')
    a = ap.parse_args(argv)
    if a.cmd == 'selftest': return selftest()
    if a.cmd == 'pack': return pack(a.inputs, a.out, max(a.padding, 0), a.pot)
    if a.cmd == 'aseprite': return aseprite(a.file, a.out)
    game = Path(a.game_dir).resolve()
    if not game.is_dir(): die(f'game dir not found: {game}')
    return {'placeholder': lambda: placeholder(game, a), 'placeholders': lambda: placeholders(game), 'lint': lambda: lint(game)}[a.cmd]()


